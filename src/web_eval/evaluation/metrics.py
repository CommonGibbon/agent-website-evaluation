def _evaluate_contrastive_match(actual_output: str, profile_a: str, profile_b: str, criteria_name: str) -> str:
    """
    Generic judge function. 
    Presents the LLM with the actual output from an agent and two potential profiles (A and B).
    Asks the LLM to determine which profile best matches the output based on the given criteria.
    Returns 'A' or 'B'.
    """
    client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])
    
    prompt = f"""
    You are an expert behavioral analyst.
    
    I have an agent who performed a task on a website. 
    I will provide you with the **Actual Output** (logs/thoughts/actions) generated by this agent.
    I will also provide two **Expected {criteria_name} Profiles** (Profile A and Profile B).
    
    Your goal is to determine which Profile best aligns with the Actual Output.
    
    --- ACTUAL OUTPUT ---
    {actual_output}
    ---------------------
    
    --- PROFILE A ---
    {profile_a}
    -----------------
    
    --- PROFILE B ---
    {profile_b}
    -----------------
    
    Based on the {criteria_name}, which profile is the most likely match?
    Respond ONLY with the single character 'A' or 'B'.
    """
    
    try:
        response = client.models.generate_content(
            model='gemini-2.5-flash', 
            contents=prompt
        )
        
        answer = response.text.strip().upper()
        # Basic cleanup if the model is chatty (e.g. "Answer: A")
        if "A" in answer and "B" not in answer:
            return "A"
        if "B" in answer and "A" not in answer:
            return "B"
        
        return answer if answer in ["A", "B"] else "A" # Default fallback if unclear
    except Exception as e:
        print(f"Error in LLM call: {e}")
        return "A" # Fallback on error


def _process_single_comparison(
    target_id: str,
    actual_output: str,
    target_profile: str,
    distractor_case: EvalCase,
    config: MetricConfig
) -> Tuple[str, bool, str]:
    """
    Helper function to run a single comparison.
    Returns (target_id, is_correct, distractor_id).
    """
    # Render the distractor profile using the config template
    distractor_profile = config.template.format(persona=distractor_case.persona)
    
    # Randomize order
    is_target_a = random.choice([True, False])
    
    if is_target_a:
        profile_a = target_profile
        profile_b = distractor_profile
        correct_option = "A"
    else:
        profile_a = distractor_profile
        profile_b = target_profile
        correct_option = "B"
        
    choice = _evaluate_contrastive_match(
        actual_output=actual_output,
        profile_a=profile_a,
        profile_b=profile_b,
        criteria_name=config.name
    )
    
    return target_id, (choice == correct_option), distractor_case.persona.id


def run_metric_eval(cases: List[EvalCase], config: MetricConfig) -> Dict[str, float]:
    """
    Generic engine for contrastive evaluation.
    Iterates through every agent (target) and compares them against every other agent (distractor).
    Uses the provided profile_builder to generate the "Expected Profile" text.
    """
    scores = {}
    print(f"\n--- Running {config.name} ---")
    
    # Pre-compute target data
    target_data = {}
    for case in cases:
        actual_output = "\n".join(case.log_data.get('action_list', []))
        for feedback in case.log_data.get('feedback', []):
            actual_output += f"\nQ: {feedback['question']}\nA: {feedback['answer']}"
        
        target_data[case.persona.id] = {
            "actual_output": actual_output,
            "profile": config.template.format(persona=case.persona)
        }
        
    results_agg = defaultdict(lambda: {"correct": 0, "total": 0})
    
    # Create tasks
    tasks = []
    for target_case in cases:
        t_id = target_case.persona.id
        t_data = target_data[t_id]
        
        for distractor_case in cases:
            if distractor_case.persona.id == t_id:
                continue
                
            tasks.append({
                "target_id": t_id,
                "actual_output": t_data["actual_output"],
                "target_profile": t_data["profile"],
                "distractor_case": distractor_case,
                "config": config
            })

    # Execute in parallel
    # Using max_workers=10 to respect potential rate limits, adjust as needed
    with ThreadPoolExecutor(max_workers=10) as executor:
        futures = [executor.submit(_process_single_comparison, **task) for task in tasks]
        
        if Progress:
            with Progress() as progress:
                task_id = progress.add_task(f"[cyan]{config.name}...", total=len(futures)) 
                for future in as_completed(futures):
                    try:
                        t_id, is_correct, d_id = future.result()
                        results_agg[t_id]["total"] += 1
                        if is_correct:
                            results_agg[t_id]["correct"] += 1
                        progress.advance(task_id)
                    except Exception as e:
                        print(f"Error processing comparison: {e}")
                        progress.advance(task_id)
        else:
            # Fallback without progress bar
            completed = 0
            for future in as_completed(futures):
                try:
                    t_id, is_correct, d_id = future.result()
                    results_agg[t_id]["total"] += 1
                    if is_correct:
                        results_agg[t_id]["correct"] += 1
                    completed += 1
                    print(f"Completed {completed}/{len(tasks)} comparisons", end='\r')
                except Exception as e:
                    print(f"Error processing comparison: {e}")
            print()

    # Calculate scores
    for t_id, stats in results_agg.items():
        if stats["total"] > 0:
            scores[t_id] = round(stats["correct"] / stats["total"], 2)
        else:
            scores[t_id] = 0.0
            
    return scores
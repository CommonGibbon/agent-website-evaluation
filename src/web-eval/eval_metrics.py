def _evaluate_contrastive_match(actual_output: str, profile_a: str, profile_b: str, criteria_name: str) -> str:
    """
    Generic judge function. 
    Presents the LLM with the actual output from an agent and two potential profiles (A and B).
    Asks the LLM to determine which profile best matches the output based on the given criteria.
    Returns 'A' or 'B'.
    """
    client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])
    
    prompt = f"""
    You are an expert behavioral analyst.
    
    I have an agent who performed a task on a website. 
    I will provide you with the **Actual Output** (logs/thoughts/actions) generated by this agent.
    I will also provide two **Expected {criteria_name} Profiles** (Profile A and Profile B).
    
    Your goal is to determine which Profile best aligns with the Actual Output.
    
    --- ACTUAL OUTPUT ---
    {actual_output}
    ---------------------
    
    --- PROFILE A ---
    {profile_a}
    -----------------
    
    --- PROFILE B ---
    {profile_b}
    -----------------
    
    Based on the {criteria_name}, which profile is the most likely match?
    Respond ONLY with the single character 'A' or 'B'.
    """
    
    response = client.models.generate_content(
        model='gemini-2.5-flash', 
        contents=prompt
    )
    
    answer = response.text.strip().upper()
    # Basic cleanup if the model is chatty (e.g. "Answer: A")
    if "A" in answer and "B" not in answer:
        return "A"
    if "B" in answer and "A" not in answer:
        return "B"
    
    return answer if answer in ["A", "B"] else "A" # Default fallback if unclear


def run_contrastive_eval_loop(
    cases: List[EvalCase], 
    profile_builder: Callable[[Persona], str], 
    metric_name: str
) -> Dict[str, float]:
    """
    Generic engine for contrastive evaluation.
    Iterates through every agent (target) and compares them against every other agent (distractor).
    Uses the provided profile_builder to generate the "Expected Profile" text.
    """
    scores = {}
    print(f"\n--- Running {metric_name} Evaluation ---")
    
    for target_case in cases:
        correct_matches = 0
        comparisons = 0
        
        # Construct Actual Output
        actual_output = "\n".join(target_case.log_data.get('action_list', []))
        for feedback in target_case.log_data.get('feedback', []):
             actual_output += f"\nQ: {feedback['question']}\nA: {feedback['answer']}"
        
        actual_output = actual_output
        
        target_profile = profile_builder(target_case.persona)
        
        for distractor_case in cases:
            if distractor_case.persona.id == target_case.persona.id:
                continue
                
            distractor_profile = profile_builder(distractor_case.persona)
            
            # Randomize order
            is_target_a = random.choice([True, False])
            
            if is_target_a:
                profile_a = target_profile
                profile_b = distractor_profile
                correct_option = "A"
            else:
                profile_a = distractor_profile
                profile_b = target_profile
                correct_option = "B"
                
            choice = _evaluate_contrastive_match(
                actual_output=actual_output,
                profile_a=profile_a,
                profile_b=profile_b,
                criteria_name=metric_name
            )
            
            if choice == correct_option:
                correct_matches += 1
            comparisons += 1
            
            print(f"  [{metric_name}] Target: {target_case.persona.id} | Distractor: {distractor_case.persona.id} | Result: {'PASS' if choice == correct_option else 'FAIL'}")

        if comparisons > 0:
            scores[target_case.persona.id] = round(correct_matches / comparisons, 2)
        else:
            scores[target_case.persona.id] = 0.0
            
    return scores

# --- Psychographics Metric ---

def _build_psychographics_profile(persona: Persona) -> str:
    return f"""
    Psychographics: {persona.psychographics}
    """

def psychographics_match(cases: List[EvalCase]) -> Dict[str, float]:
    return run_contrastive_eval_loop(
        cases=cases,
        profile_builder=_build_psychographics_profile,
        metric_name="Psychographics Alignment"
    )


